#!/usr/bin/env node
// anymodel bot: stdio MCP front for the bundled Cua Driver (MIT, part of anymodel bot).
//
// DSH's mcp-client launches this script instead of `cua-driver mcp` directly. It:
//  1. asks the bundled binary which tools exist on this platform (`cua-driver list-tools`),
//  2. writes a bounded-mode capability manifest (v3) allowing only our reviewed tool set
//     (intersected with what exists; unknown names would make the driver refuse to start),
//  3. runs `cua-driver mcp` with CUA_DRIVER_PERMISSION_MODE=bounded + that manifest,
//  4. hides every other tool from tools/list (the full list is ~230 KB of schemas) and
//     refuses calls to them before they reach the driver,
//  5. restarts the driver transparently before the manifest's 24 h lifetime runs out.
// Never passes --dangerously-bypass-approvals; telemetry and update checks are off.
// Config comes from the JSON file named by AMB_CUA_CONFIG (written by the host):
//   { bin, manifest, tools: string[], apps: [{executable}|{bundle_id}], display: boolean, direct?: boolean }
import { spawn, execFileSync } from 'node:child_process'
import fs from 'node:fs'
import readline from 'node:readline'
import { fileURLToPath } from 'node:url'

const LIFETIME_MS = 23 * 3600_000

const yq = (s) => JSON.stringify(String(s))

/** Bounded-mode capability manifest (YAML, version 3). */
export function manifestYaml({ tools, apps = [], display = false }) {
  const lines = ['# generated by anymodel bot; do not edit', 'version: 3', 'expires_after: 24h', 'idle_timeout: 24h', 'allow:', '  tools:']
  for (const t of tools) lines.push(`    - ${yq(t)}`)
  lines.push('resources:')
  if (apps.length) {
    lines.push('  apps:')
    for (const a of apps) {
      lines.push(a.bundle_id ? `    - bundle_id: ${yq(a.bundle_id)}` : `    - executable: ${yq(a.executable)}`)
      lines.push('      launch: true', '      windows: all', '      terminate: driver_launched')
    }
  }
  lines.push('  desktop:', `    display: ${display ? 'true' : 'false'}`)
  return lines.join('\n') + '\n'
}

/** Parse `cua-driver list-tools` output ("name: description" per line). */
export function parseToolList(text) {
  const out = new Set()
  for (const line of String(text).split(/\r?\n/)) {
    const m = /^([a-z][a-z0-9_]*):\s/.exec(line)
    if (m) out.add(m[1])
  }
  return out
}

/** Environment for the driver: what we were given, minus our own config, plus the hard settings. */
export function childEnv(base, cfg) {
  const env = { ...base }
  for (const k of Object.keys(env)) {
    if (k.startsWith('AMB_') || k === 'ELECTRON_RUN_AS_NODE' || /KEY|PASSWORD|SECRET|TOKEN/i.test(k)) delete env[k]
  }
  delete env.CUA_DRIVER_DANGEROUSLY_BYPASS_APPROVALS
  Object.assign(env, {
    CUA_DRIVER_PERMISSION_MODE: 'bounded',
    CUA_DRIVER_CAPABILITY_MANIFEST_FILE: cfg.manifest,
    CUA_DRIVER_CAPABILITY_MANIFEST_APPROVED: '1',
    CUA_DRIVER_DISABLE_RUN_SCRIPT: '1',
    DO_NOT_TRACK: '1',
    CUA_TELEMETRY_ENABLED: '0',
    CUA_DRIVER_RS_TELEMETRY_ENABLED: '0',
  })
  return env
}

/** Line filter between the MCP client and the driver. Pure (no I/O) so it can be unit-tested. */
export function createFilter(allowed) {
  const listIds = new Set()
  return {
    /** client → driver: returns { forward?: msg, reply?: msg } */
    fromClient(msg) {
      if (msg && msg.method === 'tools/list' && msg.id !== undefined) listIds.add(msg.id)
      if (msg && msg.method === 'tools/call' && msg.id !== undefined) {
        const name = String(msg.params?.name ?? '')
        if (!allowed.has(name)) {
          return { reply: { jsonrpc: '2.0', id: msg.id, result: { isError: true, content: [{ type: 'text', text: `Tool '${name}' is not enabled in anymodel bot's Computer Use (Cua Driver).` }] } } }
        }
      }
      return { forward: msg }
    },
    /** driver → client */
    fromDriver(msg) {
      if (msg && msg.id !== undefined && listIds.has(msg.id) && msg.result && Array.isArray(msg.result.tools)) {
        listIds.delete(msg.id)
        return { ...msg, result: { ...msg.result, tools: msg.result.tools.filter((t) => allowed.has(t.name)) } }
      }
      return msg
    },
  }
}

function main() {
  const cfg = JSON.parse(fs.readFileSync(process.env.AMB_CUA_CONFIG, 'utf8'))
  const env = childEnv(process.env, cfg)
  let available
  try {
    available = parseToolList(execFileSync(cfg.bin, ['list-tools'], { env, encoding: 'utf8', timeout: 30_000, stdio: ['ignore', 'pipe', 'ignore'] }))
  } catch (e) {
    process.stderr.write(`amb-cua-mcp: cua-driver list-tools failed: ${e?.message ?? e}\n`)
    process.exit(1)
  }
  const tools = cfg.tools.filter((t) => available.has(t))
  const allowed = new Set(tools)
  fs.writeFileSync(cfg.manifest, manifestYaml({ tools, apps: cfg.apps ?? [], display: !!cfg.display }), { mode: 0o600 })
  const filter = createFilter(allowed)
  const args = ['mcp', ...(cfg.direct ? ['--direct'] : [])]

  let child
  let startedAt = 0
  let initMsg
  let initializedMsg
  const pending = new Set()
  const send = (msg) => process.stdout.write(JSON.stringify(msg) + '\n')

  const start = (replay) => {
    startedAt = Date.now()
    const c = spawn(cfg.bin, args, { env, stdio: ['pipe', 'pipe', 'inherit'] })
    child = c
    const rl = readline.createInterface({ input: c.stdout })
    rl.on('line', (line) => {
      if (!line.trim()) return
      let msg
      try { msg = JSON.parse(line) } catch { return }
      if (typeof msg.id === 'string' && msg.id.startsWith('amb-reinit-')) return
      if (msg.id !== undefined && (msg.result !== undefined || msg.error !== undefined)) pending.delete(msg.id)
      send(filter.fromDriver(msg))
    })
    c.on('exit', (code) => {
      if (child !== c) return
      child = undefined
      for (const id of pending) send({ jsonrpc: '2.0', id, error: { code: -32603, message: `cua-driver exited (${code})` } })
      pending.clear()
    })
    if (replay && initMsg) {
      c.stdin.write(JSON.stringify({ ...initMsg, id: `amb-reinit-${startedAt}` }) + '\n')
      if (initializedMsg) c.stdin.write(JSON.stringify(initializedMsg) + '\n')
    }
  }
  start(false)

  const rl = readline.createInterface({ input: process.stdin })
  rl.on('line', (line) => {
    if (!line.trim()) return
    let msg
    try { msg = JSON.parse(line) } catch { return }
    if (msg.method === 'initialize') initMsg = msg
    if (msg.method === 'notifications/initialized') initializedMsg = msg
    const r = filter.fromClient(msg)
    if (r.reply) return send(r.reply)
    // The manifest lives at most 24 h: start a fresh driver (same manifest) before it expires.
    if (child && msg.method === 'tools/call' && Date.now() - startedAt > LIFETIME_MS) {
      const old = child
      child = undefined
      for (const id of pending) send({ jsonrpc: '2.0', id, error: { code: -32603, message: 'cua-driver restarted' } })
      pending.clear()
      old.kill()
    }
    if (!child) start(msg.method !== 'initialize')
    if (msg.id !== undefined && msg.method) pending.add(msg.id)
    child.stdin.write(JSON.stringify(r.forward) + '\n')
  })
  rl.on('close', () => { child?.kill(); process.exit(0) })
  for (const s of ['SIGTERM', 'SIGINT']) process.on(s, () => { child?.kill(); process.exit(0) })
}

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) main()
